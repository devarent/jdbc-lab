package lab;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Statement;

public final class JdbcLab {
    public static void main(String[] args) throws Exception {
        String url = env("JDBC_URL", "jdbc:postgresql://localhost:5432/lab");
        String user = env("JDBC_USER", "lab");
        String password = env("JDBC_PASSWORD", "labpassword");

        try (Connection connection = DriverManager.getConnection(url, user, password)) {
            var meta = connection.getMetaData();
            System.out.println("Connected to " + meta.getDatabaseProductName()
                    + " " + meta.getDatabaseProductVersion());

            try (Statement statement = connection.createStatement()) {
                statement.execute("CREATE TABLE IF NOT EXISTS lab_notes ("
                        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                        + "topic VARCHAR(120) NOT NULL, "
                        + "note TEXT NOT NULL, "
                        + "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
            }

            try (PreparedStatement insert = connection.prepareStatement(
                    "INSERT INTO lab_notes (topic, note) VALUES (?, ?)")) {
                insert.setString(1, "jdbc");
                insert.setString(2, "Connected with a plain JDBC URL, no ORM.");
                insert.executeUpdate();
            }

            try (Statement statement = connection.createStatement();
                 ResultSet rows = statement.executeQuery(
                         "SELECT id, topic, note FROM lab_notes ORDER BY id DESC LIMIT 5")) {
                while (rows.next()) {
                    System.out.printf("%d | %s | %s%n",
                            rows.getLong("id"), rows.getString("topic"), rows.getString("note"));
                }
            }
        }
    }

    private static String env(String key, String fallback) {
        String value = System.getenv(key);
        return value == null || value.isBlank() ? fallback : value;
    }
}
